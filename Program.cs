// =========================
// ADMIN AUTHORIZATION
// =========================

static bool IsAdminAuthorized(
    HttpRequest request,
    string adminApiKey)
{
    if (!request.Headers.TryGetValue(
            "X-Admin-Key",
            out var suppliedKey))
    {
        return false;
    }

    return string.Equals(
        suppliedKey.ToString(),
        adminApiKey,
        StringComparison.Ordinal);
}


// =========================
// LICENSE KEY GENERATOR
// =========================

static string GenerateLicenseKey()
{
    const string chars =
        "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";

    string CreatePart()
    {
        var bytes =
            RandomNumberGenerator.GetBytes(4);

        var result =
            new char[4];

        for (int i = 0; i < 4; i++)
        {
            result[i] =
                chars[
                    bytes[i] % chars.Length];
        }

        return new string(result);
    }

    return
        $"DCP-{CreatePart()}-{CreatePart()}-{CreatePart()}";
}


// =========================
// DATABASE
// =========================

public class LicenseDbContext : DbContext
{
    public LicenseDbContext(
        DbContextOptions<LicenseDbContext> options)
        : base(options)
    {
    }

    public DbSet<LicenseKey> LicenseKeys =>
        Set<LicenseKey>();

    protected override void OnModelCreating(
        ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<LicenseKey>(
            entity =>
            {
                entity.ToTable("LicenseKeys");

                entity.HasKey(x => x.Id);

                entity.Property(x => x.Key)
                    .IsRequired()
                    .HasMaxLength(50);

                entity.HasIndex(x => x.Key)
                    .IsUnique();

                entity.Property(x => x.IsUsed)
                    .IsRequired();

                entity.Property(x => x.DeviceId)
                    .HasMaxLength(255);

                entity.Property(x => x.CreatedAt)
                    .IsRequired();
            });
    }
}


