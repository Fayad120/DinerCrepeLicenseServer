// CREATE LICENSE KEYS
// =========================

app.MapPost(
    "/api/license/create",
    async (
        HttpRequest httpRequest,
        LicenseDbContext db,
        int count) =>
{
    if (!IsAdminAuthorized(httpRequest, adminApiKey))
    {
        return Results.Unauthorized();
    }

    if (count < 1 || count > 1000)
    {
        return Results.BadRequest(new
        {
            success = false,
            message =
                "عدد المفاتيح يجب أن يكون بين 1 و1000."
        });
    }

    var keys =
        new List<string>();

    for (int i = 0; i < count; i++)
    {
        string key;

        do
        {
            key =
                GenerateLicenseKey();
        }
        while (
            await db.LicenseKeys
                .AnyAsync(x => x.Key == key));

        db.LicenseKeys.Add(
            new LicenseKey
            {
                Key = key,
                IsUsed = false,
                CreatedAt = DateTime.UtcNow
            });

        keys.Add(key);
    }

    await db.SaveChangesAsync();

    return Results.Ok(new
    {
        success = true,
        count = keys.Count,
        keys
    });
});


