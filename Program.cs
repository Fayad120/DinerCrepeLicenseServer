app.MapGet(
    "/api/license/all",
    async (
        HttpRequest httpRequest,
        LicenseDbContext db) =>
{
    if (!IsAdminAuthorized(httpRequest, adminApiKey))
    {
        return Results.Unauthorized();
    }

    var licenses =
        await db.LicenseKeys
            .OrderByDescending(
                x => x.CreatedAt)
            .Select(x => new
            {
                id = x.Id,
                key = x.Key,
                isUsed = x.IsUsed,
                deviceId = x.DeviceId,
                createdAt = x.CreatedAt,
                activatedAt = x.ActivatedAt
            })
            .ToListAsync();

    return Results.Ok(new
    {
        success = true,
        count = licenses.Count,
        licenses
    });
});


// =========================
// ACTIVATE LICENSE
// =========================

app.MapPost(
    "/api/license/activate",
    async (
        LicenseDbContext db,
        ActivateLicenseRequest request) =>
{
    if (string.IsNullOrWhiteSpace(request.Key))
    {
        return Results.BadRequest(new
        {
            success = false,
            message = "مفتاح الترخيص مطلوب."
        });
    }

    if (string.IsNullOrWhiteSpace(request.DeviceId))
    {
        return Results.BadRequest(new
        {
            success = false,
            message = "معرف الجهاز مطلوب."
        });
    }

    string normalizedKey =
        request.Key
            .Trim()
            .ToUpperInvariant();

    string deviceId =
        request.DeviceId.Trim();

    var license =
        await db.LicenseKeys
            .FirstOrDefaultAsync(
                x => x.Key == normalizedKey);

    if (license == null)
    {
        return Results.Ok(new
        {
            success = false,
            message =
                "مفتاح الترخيص غير صحيح."
        });
    }

    if (license.IsUsed)
    {
        if (string.Equals(
                license.DeviceId,
                deviceId,
                StringComparison.Ordinal))
        {
            return Results.Ok(new
            {
                success = true,
                message =
                    "الترخيص مفعل بالفعل على هذا الجهاز.",
                activatedAt =
                    license.ActivatedAt
            });
        }

        return Results.Ok(new
        {
            success = false,
            message =
                "هذا المفتاح مرتبط بجهاز آخر."
        });
    }

    license.IsUsed = true;
    license.DeviceId = deviceId;
    license.ActivatedAt =
        DateTime.UtcNow;

    await db.SaveChangesAsync();

    return Results.Ok(new
    {
        success = true,
        message =
            "تم تفعيل البرنامج بنجاح.",
        activatedAt =
            license.ActivatedAt
    });
});


